def plan_moves(world, deadline=None):
    def expired():
        return deadline is not None and time.perf_counter() > deadline

    def time_left():
        if deadline is None:
            return 10**9
        return deadline - time.perf_counter()

    def allow_heavy_phase():
        return time_left() > HEAVY_PHASE_MIN_TIME and len(world.planets) <= HEAVY_ROUTE_PLANET_LIMIT

    modes = build_modes(world)
    policy = build_policy_state(world, deadline=deadline)
    planned_commitments = defaultdict(list)
    missions = []
    moves = []
    spent_total = defaultdict(int)

    def source_inventory_left(source_id):
        return world.source_inventory_left(source_id, spent_total)

    def source_attack_left(source_id):
        return policy["attack_budget"].get(source_id, 0) - spent_total[source_id]

    def append_move(src_id, angle, ships):
        send = min(int(ships), source_inventory_left(src_id))
        if send < 1:
            return 0
        moves.append([src_id, float(angle), int(send)])
        spent_total[src_id] += send
        return send

    def finalize_moves():
        final_moves = []
        used_final = defaultdict(int)
        for src_id, angle, ships in moves:
            source = world.planet_by_id[src_id]
            max_allowed = int(source.ships) - used_final[src_id]
            send = min(int(ships), max_allowed)
            if send >= 1:
                final_moves.append([src_id, float(angle), int(send)])
                used_final[src_id] += send
        return final_moves

    # Attack all static neutral planets with everything, ignoring distance
    targets = sorted(
        [p for p in world.neutral_planets if world.is_static(p.id)],
        key=lambda t: (-t.production, t.id)  # highest production first
    )
    if not targets:
        return []

    for src in world.my_planets:
        if expired():
            return finalize_moves()
        available = source_attack_left(src.id)
        if available <= 0:
            continue

        for target in targets:
            if expired():
                return finalize_moves()
            if target.id == src.id:
                continue

            seeded = world.best_probe_aim(src.id, target.id, available, hints=(available,))
            if seeded is None:
                continue
            _, (angle, turns, _, _) = seeded

            # Compute needed ships to capture assuming no other arrivals (rush ignores others)
            need = world.ships_needed_to_capture(target.id, turns, planned_commitments=planned_commitments)
            if need <= 0:
                continue

            # Send as many as we can, at least need
            send = min(available, max(need, int(available * 0.9)))  # almost all
            plan = settle_plan(src, target, available, send, world, planned_commitments, modes, policy, mission="capture")
            if plan is None:
                continue

            angle, turns, _, need, actual_send = plan
            if actual_send >= need:
                sent = append_move(src.id, angle, actual_send)
                if sent >= need:
                    planned_commitments[target.id].append((turns, world.player, int(sent)))
            # Only one target per source to spread attacks? No, rusher wants many attacks from same source? Let's allow multiple if budget remains.
            # After sending, recalc available for next iteration
            available = source_attack_left(src.id)
            if available <= 0:
                break

    return finalize_moves()

